export const GLYPH_W = 5;
export const GLYPH_H = 8;
export const ADVANCE = 6;

/** A W x H grid of 0..1 brightness values. */
export class PixelGrid {
  constructor(w, h) {
    this.w = w;
    this.h = h;
    this.data = new Float32Array(w * h);
  }

  clear() {
    this.data.fill(0);
  }

  set(x, y, v) {
    if (x >= 0 && y >= 0 && x < this.w && y < this.h) this.data[y * this.w + x] = Math.max(this.data[y * this.w + x], v);
  }

  /** Draw text with the 5x7 font; `scale` repeats every pixel. Returns the x just after the last glyph. */
  text(str, x, y, v = 1, scale = 1) {
    let cx = x;
    for (const ch of str) {
      const glyph = GLYPHS[ch] ?? GLYPHS[' '];
      for (let gy = 0; gy < GLYPH_H; gy += 1) {
        for (let gx = 0; gx < GLYPH_W; gx += 1) {
          if (glyph[gy][gx] !== '#') continue;
          for (let sy = 0; sy < scale; sy += 1) for (let sx = 0; sx < scale; sx += 1) this.set(cx + gx * scale + sx, y + gy * scale + sy, v);
        }
      }
      cx += ADVANCE * scale;
    }
    return cx;
  }

  rect(x, y, w, h, v = 1) {
    for (let j = 0; j < h; j += 1) for (let i = 0; i < w; i += 1) this.set(x + i, y + j, v);
  }

  /** Dotted horizontal rule. */
  rule(x, y, w, v = 0.35, every = 2) {
    for (let i = 0; i < w; i += every) this.set(x + i, y, v);
  }

  /** Draw an ASCII sprite: '#' full, '+' half, anything else off. */
  sprite(rows, x, y, v = 1) {
    rows.forEach((row, j) => {
      [...row].forEach((c, i) => {
        if (c === '#') this.set(x + i, y + j, v);
        else if (c === '+') this.set(x + i, y + j, v * 0.5);
      });
    });
  }

  /**
   * Paint onto a 2D canvas as discrete lit pixels (cell px each, gap px of dark between).
   * `tint` is [r,g,b] 0-255 for a fully lit pixel.
   */
  paint(ctx, cell, gap, tint) {
    ctx.fillStyle = '#000';
    ctx.fillRect(0, 0, this.w * cell, this.h * cell);
    const r = Math.max(0.6, (cell - gap) * 0.18);
    for (let y = 0; y < this.h; y += 1) {
      for (let x = 0; x < this.w; x += 1) {
        const v = this.data[y * this.w + x];
        // faint unlit-pixel structure, so the panel reads as a real dot-matrix
        const base = v > 0 ? v : 0;
        ctx.fillStyle = base > 0 ? `rgb(${Math.round(tint[0] * base)},${Math.round(tint[1] * base)},${Math.round(tint[2] * base)})` : 'rgb(9,8,5)';
        ctx.beginPath();
        ctx.roundRect(x * cell + gap / 2, y * cell + gap / 2, cell - gap, cell - gap, r);
        ctx.fill();
      }
    }
  }
}
